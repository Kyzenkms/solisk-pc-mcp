const { contextBridge, ipcRenderer } = require("electron");

contextBridge.exposeInMainWorld("mcp", {
  getStatus:          () => ipcRenderer.invoke("get-status"),
  getHealth:          () => ipcRenderer.invoke("get-health"),
  getConfig:          () => ipcRenderer.invoke("get-config"),
  getLogs:            () => ipcRenderer.invoke("get-logs"),
  clearLogs:          () => ipcRenderer.invoke("clear-logs"),
  startServer:        () => ipcRenderer.invoke("start-server"),
  stopServer:         () => ipcRenderer.invoke("stop-server"),
  retryRelay:         () => ipcRenderer.invoke("retry-relay"),
  relaySet:           (e) => ipcRenderer.invoke("relay-set", e),
  regenerateMcpUrl:   () => ipcRenderer.invoke("regenerate-mcp-url"),
  saveConfig:         (c) => ipcRenderer.invoke("save-config", c),
  writeClipboard:     (t) => ipcRenderer.invoke("write-clipboard", t),
  openUrl:            (u) => ipcRenderer.invoke("open-url", u),
  minimize:           () => ipcRenderer.invoke("minimize"),
  maximize:           () => ipcRenderer.invoke("maximize"),
  close:              () => ipcRenderer.invoke("close-win"),
  quit:               () => ipcRenderer.invoke("quit-app"),
  onStatus: (fn) => { ipcRenderer.on("status", (_, d) => fn(d)); },
  onLog:    (fn) => { ipcRenderer.on("log",    (_, d) => fn(d)); },
  onConfig: (fn) => { ipcRenderer.on("config", (_, d) => fn(d)); },
  onShellApprovalReq: (fn) => { ipcRenderer.on("shell-approval-req", (_, d) => fn(d)); },
  sendShellApprovalRes: (data) => ipcRenderer.invoke("shell-approval-res", data),
  relayListKeys:    () => ipcRenderer.invoke("relay-list-keys"),
  relayCreateKey:   (p) => ipcRenderer.invoke("relay-create-key", p),
  relayRevokeKey:   (k) => ipcRenderer.invoke("relay-revoke-key", k),
  relaySetMode:     (m) => ipcRenderer.invoke("relay-set-mode", m),
  configDiagnose:   () => ipcRenderer.invoke("config-diagnose"),
  configRepair:     () => ipcRenderer.invoke("config-repair"),
  configRestore:    (p) => ipcRenderer.invoke("config-restore", p),
  configBackup:     () => ipcRenderer.invoke("config-backup"),
  configOpenFolder: () => ipcRenderer.invoke("config-open-folder"),
  tunnelState:      () => ipcRenderer.invoke("tunnel-state"),
  tunnelSetMode:    (m) => ipcRenderer.invoke("tunnel-set-mode", m),
  tunnelInstall:    () => ipcRenderer.invoke("tunnel-install"),
  tunnelLogin:      () => ipcRenderer.invoke("tunnel-login-start"),
  tunnelCreate:     (n) => ipcRenderer.invoke("tunnel-create", n),
  tunnelRoute:      (h) => ipcRenderer.invoke("tunnel-route", h),
  tunnelForget:     () => ipcRenderer.invoke("tunnel-forget"),
  tailscaleServe:   (f) => ipcRenderer.invoke("tailscale-serve", f),
  tailscaleOff:     () => ipcRenderer.invoke("tailscale-off"),
  dashSet:          (e) => ipcRenderer.invoke("dash-set", e),
  onUpdateAvailable: (fn) => { ipcRenderer.on("update-available", (_, d) => fn(d)); },
  checkUpdates:     () => ipcRenderer.invoke("check-updates-now"),
  skipUpdate:       (v) => ipcRenderer.invoke("skip-update", v),
});
